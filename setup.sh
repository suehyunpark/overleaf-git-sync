#!/usr/bin/env bash
# One-time setup to sync the current git repo with an Overleaf project:
#   - add `overleaf` remote (with your personal token)
#   - install pre-push hook (atomic: Overleaf first, then origin)
#   - add convenience aliases (git olp / olf / ols)
#
# Usage:
#   bash setup.sh                      # interactive (prompts for project ID + token)
#   bash setup.sh <project_id>         # project ID via arg; prompts for token
#   OVERLEAF_PROJECT_ID=... OVERLEAF_TOKEN=... bash setup.sh   # fully non-interactive
#
# Re-running is safe (idempotent). Project ID is persisted to .overleaf-sync
# (tracked, not a secret) so collaborators only need to enter their token.

set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")"

CONFIG_FILE=".overleaf-sync"
DEFAULT_OVERLEAF_BRANCH="master"

# 1. Resolve project ID: arg > env > config file > prompt.
if [[ $# -ge 1 && -n "$1" ]]; then
  OVERLEAF_PROJECT_ID="$1"
elif [[ -n "${OVERLEAF_PROJECT_ID:-}" ]]; then
  :  # use env
elif [[ -f "$CONFIG_FILE" ]]; then
  # shellcheck disable=SC1090
  source "$CONFIG_FILE"
fi

if [[ -z "${OVERLEAF_PROJECT_ID:-}" ]]; then
  echo "Find your Overleaf project ID in the project URL:"
  echo "  https://www.overleaf.com/project/<PROJECT_ID>"
  echo
  read -rp "Overleaf project ID: " OVERLEAF_PROJECT_ID
fi

if [[ ! "$OVERLEAF_PROJECT_ID" =~ ^[a-f0-9]{24}$ ]]; then
  echo "error: project ID must be 24 lowercase hex chars (got: '$OVERLEAF_PROJECT_ID')." >&2
  exit 1
fi

# 2. Resolve token: env > prompt. Never persisted to tracked files.
if [[ -z "${OVERLEAF_TOKEN:-}" ]]; then
  echo
  echo "Create your Overleaf git token (one-time, per user):"
  echo "  Overleaf → Account Settings → Git Integration → Create Token"
  echo
  read -rsp "Paste your Overleaf token (starts with olp_): " OVERLEAF_TOKEN
  echo
fi

if [[ -z "$OVERLEAF_TOKEN" || ! "$OVERLEAF_TOKEN" =~ ^olp_ ]]; then
  echo "error: token missing or doesn't start with 'olp_'." >&2
  exit 1
fi

OVERLEAF_URL="https://git:${OVERLEAF_TOKEN}@git.overleaf.com/${OVERLEAF_PROJECT_ID}"

# 3. Overleaf remote
if git remote | grep -q '^overleaf$'; then
  git remote set-url overleaf "$OVERLEAF_URL"
else
  git remote add overleaf "$OVERLEAF_URL"
fi
echo "✓ overleaf remote set"

# 3b. Discover the branch selected as the Overleaf project's default branch.
# Older projects use master; newer projects commonly use main.  Do not assume
# either one: all aliases and the hook must target the branch advertised by
# the remote's HEAD.
OVERLEAF_BRANCH="$(git ls-remote --symref overleaf HEAD 2>/dev/null | awk '$1 == "ref:" && $2 ~ /^refs\/heads\// && $3 == "HEAD" { sub("refs/heads/", "", $2); print $2; exit }')"
if [[ -z "$OVERLEAF_BRANCH" ]]; then
  OVERLEAF_BRANCH="$DEFAULT_OVERLEAF_BRANCH"
  echo "warning: could not determine Overleaf's default branch; using '$OVERLEAF_BRANCH'." >&2
else
  echo "✓ Overleaf default branch = $OVERLEAF_BRANCH"
fi

# 4. Persist project ID (not secret) so re-clones skip the prompt
cat > "$CONFIG_FILE" <<EOF
# Auto-generated by setup.sh. Tracked. Project ID is not a secret.
# Token is NEVER stored here — it lives only in .git/config remote URL.
OVERLEAF_PROJECT_ID="$OVERLEAF_PROJECT_ID"
OVERLEAF_BRANCH="$OVERLEAF_BRANCH"
EOF
echo "✓ $CONFIG_FILE written (commit this so collaborators only need their token)"

# 5. Wipe any previous multi-push config on origin. We rely on the pre-push
#    hook for atomicity, NOT on multi-push URLs (which are non-atomic — a
#    failed Overleaf push still lets the primary remote push proceed).
if git remote | grep -q '^origin$'; then
  # Drop every push URL so origin pushes to its fetch URL again. (`git remote
  # set-url --push` refuses to overwrite more than one existing push URL.)
  if git config --get-all remote.origin.pushurl 2>/dev/null | grep -q .; then
    git config --unset-all remote.origin.pushurl
  fi
  echo "✓ origin push URL = single (primary remote only); Overleaf push via pre-push hook"
else
  echo "note: no 'origin' remote yet. Add one (GitHub/GitLab/etc.) before pushing."
fi

# 6. Install hooks via local-only trampoline.
#    Why not core.hooksPath=.githooks + chmod +x? Because Overleaf's git
#    mirror does NOT preserve Unix mode bits — every "Update on Overleaf."
#    round-trip silently demotes .githooks/pre-push from 100755 to 100644,
#    and git ignores hooks that aren't executable. Trampoline in .git/hooks/
#    is untracked (never round-tripped), stays executable, and execs the
#    tracked .githooks/pre-push via `bash` — bash ignores the source exec bit.
git config --unset core.hooksPath 2>/dev/null || true
mkdir -p .git/hooks
cat > .git/hooks/pre-push <<'TRAMPOLINE'
#!/usr/bin/env bash
exec bash "$(git rev-parse --show-toplevel)/.githooks/pre-push" "$@"
TRAMPOLINE
chmod +x .git/hooks/pre-push
echo "✓ .git/hooks/pre-push trampoline installed (Overleaf-proof)"

# 7. Aliases
#    olp: Overleaf auto-commits on every web save, producing many tiny
#         "Update on Overleaf." commits. Rebasing local commits on top of that
#         cascade creates false conflicts. Force merge to bundle Overleaf's
#         history as one clean merge commit.
git config alias.olp "pull --no-rebase overleaf $OVERLEAF_BRANCH"
git config alias.olf 'fetch overleaf'
git config alias.ols "!git fetch overleaf && git log --oneline overleaf/$OVERLEAF_BRANCH -10"
echo "✓ aliases installed: git olp, git olf, git ols"

echo
echo "Done. Daily usage:"
echo "  git pull              # from primary remote (your pull.rebase setting respected)"
echo "  git olp               # from Overleaf (always merge; pick up web edits)"
echo "  git push              # hook pushes Overleaf first; if that fails, primary push is aborted too"
echo "  git ols               # see recent Overleaf-side commits"
echo
echo "Recovery if 'git push' is rejected (Overleaf ahead):"
echo "  git olp               # merge Overleaf changes"
echo "  # resolve conflicts if any, commit"
echo "  git push              # retry"
